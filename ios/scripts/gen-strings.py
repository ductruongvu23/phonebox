#!/usr/bin/env python3
"""Turns the Android shell's string resources (values/, values-vi/, values-el/) into the iOS Localizable.strings files, so the
two apps say the same thing in the same languages. Run after upstream changes those files; the output is committed."""
import os, re, sys
import xml.etree.ElementTree as ET

root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
res = os.path.join(root, "android", "app", "src", "main", "res")
out = os.path.join(root, "ios", "app", "Resources")
langs = {"en": "values", "vi": "values-vi", "el": "values-el"}

def convert(v):
    v = v.replace('\\"', '"').replace("\\'", "'")
    v = re.sub(r"%(\d+)\$s", r"%\1$@", v)
    return v.replace("\\", "\\\\").replace('"', '\\"').replace("\\\\n", "\\n")

for code, folder in langs.items():
    tree = ET.parse(os.path.join(res, folder, "strings.xml"))
    lines = ['/* Generated by ios/scripts/gen-strings.py from the Android string resources. Do not edit. */']
    for s in tree.getroot().iter("string"):
        lines.append('"%s" = "%s";' % (s.get("name"), convert(s.text or "")))
    d = os.path.join(out, code + ".lproj")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(code, len(lines) - 1, "strings")
